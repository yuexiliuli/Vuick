/// 全清+低清双档。取 6：中带外沿 ±10 行 ≈ 停滚点外 4-5 屏的滚回覆盖（常规回看一步到位
/// 命中低清），配合近带 ±4 行（≈2 屏）让「滚回近/中带内命中不重渲」的可观测窗口覆盖
/// 一个大滚动回合；再大内存线性增长、无额外体验收益。
pub const GRID_MBAND_ROWS: usize = 6;
