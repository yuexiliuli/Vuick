pub const GRID_QUICK_PREFETCH_INFLIGHT: usize = 8;
// ---- 网格带宽预熟（本线 M1+T6）：worker 预熟由「整本单调游标」改为「以视口中心页为
// 核心的水平带宽」——近带全清+低清双档、中带仅低清、更远不预熟。view 每次进入网格/
// 卡宽变化/滚动重定中心时把几何（中心页 + 近/中带页区间）随 SetGridPrewarm 下发 worker。
// 两条锁死的几何不变式：
//  ① 近带（每侧 [`GRID_NBAND_ROWS`] 行）⊇ view 可视带+保留窗（GRID_ROW_BUFFER=2 +
//     GRID_KEEP_ROWS=2 → 每侧 ≥4 行）——「可视带永不失图」由 view keep_range 保纹理、
//      worker 近带保位图，回看零重栅；
//  ② 中带（每侧额外 [`GRID_MBAND_ROWS`] 行）仅低清——滚回中带命中即显、不再占全清内存。
// 内存落点推导（242p 长文档、A4、default 卡宽 280px、grid_zoom=2 档卡宽 560px → 2 列）：
//   近带 ±4 行 = 9 行 × 2 列 = 18 页 × (全清 1.77MB + 低清 0.44MB ≈ 2.2MB) ≈ 40MB；
//   中带 ±6 行（中带外沿 ±10 行，中带仅 = 12 行）× 2 列 = 24 页 × 低清 0.44MB ≈ 10.6MB；
//   合计 ≈ 50MB（几十 MB 量级，且**与文档总页数无关**——242p 整本两档 ≈ 535MB 超
//   GRID_CACHE_FULL_DOC_MAX 256MB cap 触发 LRU 滑动窗/永不完成的负资产就是被本模型根治的
//   对象；scale_factor=2 + 9 列 HiDPI 退化档近带 ≈ 99MB+中带 26MB ≈ 125MB，仍远小于 256MB
//   cap、且同样有界不随页数增长，注释按 grid_zoom2/2 列主口径标 50MB）。
pub const GRID_NBAND_ROWS: usize = 4;
/// 网格**中带**行数（每侧，近带之外额外外扩的行数；中带总外沿 = 近+中 = ±10 行）。中带
